import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const model = (await readFile(new URL('store.js', root), 'utf8')).replace(/^export /gm, '');
const panel = await readFile(new URL('panel.js', root), 'utf8');
const browser = '// Generated by node build.mjs. Edit store.js / panel.js instead.\n(() => {\n' + model + '\n' + panel + '\n})();\n';
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/client.js', root), browser);
console.log('Built Idea browser plugin (no dependencies).');
