import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const read = file => readFileSync(resolve(root, file), 'utf8');
const manifest = JSON.parse(read('package.json'));
test('bundle includes native entry and distribution resources without dependencies', () => {
  assert.equal(manifest.name, 'dsh-idea-list');
  assert.equal(manifest.dsh.client.platform, 'web');
  assert.equal(manifest.private, undefined);
  assert.equal(manifest.publishConfig.access, 'public');
  assert.ok(manifest.files.includes('dist/'));
  assert.equal(manifest.exports['./client'], './dist/client.js');
  assert.match(read('cordis.patch.yml'), /name: 'dsh-idea-list'/);
  const readme = read('README.md');
  assert.match(readme, /^# 灵感清单 · dsh-idea-list/m);
  assert.match(readme, /原创插件代码、界面、图标、文档和测试全部由 AI 生成/);
  assert.ok(readme.includes('https://www.deepseek.com/zh/harness/'));
  assert.ok(readme.includes('https://github.com/deepseek-ai/deepseek-harness'));
  assert.match(readme, /非官方第三方插件/);
  for (const script of ['build', 'test', 'prepack']) assert.equal(typeof manifest.scripts[script], 'string');
  assert.equal(manifest.dependencies, undefined);
  for (const file of ['dist/client.js', 'index.js', 'icon.svg', 'cordis.patch.yml', 'README.md']) assert.ok(existsSync(resolve(root, file)));
  for (const lang of ['zh', 'en']) assert.equal(JSON.parse(read(`locale/${lang}.json`)).meta.title, '灵感清单');
  assert.match(read('dist/client.js'), /name: 'main', key: 'idea'/);
  assert.match(read('dist/client.js'), /name: 'sidebar.panellist', id: 'idea'/);
  assert.doesNotMatch(read('dist/client.js'), /fetch\(|innerHTML|dangerouslySetInnerHTML|https?:\/\//);
});
test('browser bundle matches source and keeps native font and clean lifecycle', () => {
  const expected = '// Generated by node build.mjs. Edit store.js / panel.js instead.\n(() => {\n' + read('store.js').replace(/^export /gm, '') + '\n' + read('panel.js') + '\n})();\n';
  assert.equal(read('dist/client.js'), expected);
  const panel = read('panel.js');
  assert.match(panel, /:focus-visible/);
  assert.match(panel, /max-width:640px/);
  assert.match(panel, /aria-live/);
  assert.match(panel, /isComposing/);
  assert.match(panel, /window\.navigator\.locks\.request/);
  assert.match(panel, /ctx\.effect\(\(\) => \(\) => store\.dispose\(\)\)/);
  assert.match(panel, /font-family:var\(--dsh-font-family-text,inherit\)/);
});
test('input separates concise title, long details and custom category selection', () => {
  const panel = read('panel.js');
  assert.match(panel, /'aria-label': '灵感标题'.*maxLength: MAX_TITLE/);
  assert.match(panel, /'aria-label': '具体内容'.*maxLength: MAX_CONTENT/);
  assert.match(panel, /h\(CategorySelect, \{ categories, value: categoryId/);
  assert.match(panel, /store\.add\(submitted\)/);
  assert.match(panel, /categoryId = categories\.some/);
  assert.doesNotMatch(panel, /idea-demo|DEMO|idea-empty|idea-footer|给每个灵感/);
});
test('compact category cards show only the title and open an accessible dialog', () => {
  const panel = read('panel.js');
  const cards = panel.slice(panel.indexOf('groups.map(group =>'), panel.indexOf("h('p', { role: 'status', 'aria-live'"));
  assert.match(cards, /group\.name/);
  assert.match(cards, /group\.items\.map/);
  assert.match(cards, /'aria-haspopup': 'dialog'/);
  assert.match(cards, /onClick: \(\) => setSelectedId\(item.id\)/);
  assert.match(cards, /item\.title/);
  assert.doesNotMatch(cards, /item\.content|createdAt|updatedAt|编辑|删除/);
  assert.match(cards, /className: 'idea-card-check', type: 'checkbox', checked: item.done/);
  assert.match(cards, /onChange: \(\) => run\(\(\) => store.toggle\(item.id\)/);
  assert.match(cards, /'aria-label': \(item.done \? '标为未完成：' : '标为已完成：'\)/);
  assert.match(panel, /\.idea-card\{[^}]*min-height:60px/);
  assert.doesNotMatch(panel, /min-height:152px|grid-template-areas/);
  assert.match(panel, /dialog\.showModal\(\)/);
  assert.match(panel, /if \(dialog.open\) dialog.close\(\)/);
  assert.match(panel, /onCancel: event => \{ event.preventDefault\(\); onClose\(\); \}/);
  assert.match(panel, /className: 'idea-detail-text' \}, item.content/);
  assert.match(panel, /draft.title !== item.title \|\| draft.content !== item.content/);
});
test('category management supports creation, renaming and non-destructive deletion', () => {
  const panel = read('panel.js');
  assert.match(panel, /store\.addCategory\(submitted\)/);
  assert.match(panel, /store\.renameCategory\(category.id, renameValue\)/);
  assert.match(panel, /store\.removeCategory\(deleting\)/);
  assert.match(panel, /其中的条目移至「未分类」，不会删除/);
  assert.match(panel, /h\('option', \{ value: '' \}, '未分类'\)/);
  assert.doesNotMatch(panel, /\['工作', '学习'|\['工作','学习'/);
  assert.match(panel, /'关闭删除提示', onClick: store.dismissUndo/);
});
test('semantic workshop surfaces remain opt-in and module-independent', () => {
  const panel = read('panel.js');
  assert.match(panel, /label: '灵感清单'/);
  assert.doesNotMatch(panel, /idea-logo|idea-wordmark/);
  assert.match(panel, /h\('header', \{ className: 'idea-top' \},\s*h\('h1', \{ className: 'idea-title' \}, '灵感清单'\)/);
  assert.match(panel, /'aria-label': '灵感清单'/);
  assert.match(panel, /'data-stylelab-scope': 'inspiration'/);
  assert.match(panel, /'data-stylelab-collection': 'notes'/);
  for (const surface of ['note', 'composer', 'control']) assert.ok(panel.includes(`'data-stylelab-surface': '${surface}'`));
  assert.doesNotMatch(panel, /stylelab-oat|stylelab-mist|DECOR_PALETTES|require\(['"]@local\/dsh-stylelab/);
  assert.match(read('store.js'), /STORAGE_KEY = 'dsh.local.idea.v1'/);
});
